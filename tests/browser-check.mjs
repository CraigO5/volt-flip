// Visual comparison with exact approved reference at normalized density.
const reference=await readFile('/Users/craigondevilla/.codex/generated_images/01a1b3aa-b510-7ee0-832f-2b83162a6c6c/exec-7072cbcf-e307-43ce-9f2f-9a1bdee41bdf.png');
