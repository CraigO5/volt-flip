const touchPage=await touchContext.newPage();
await touchPage.addInitScript(game=>{localStorage.setItem('vf-game',JSON.stringify(game));},fixture);
await touchPage.goto('http://127.0.0.1:4177/');
const tb=await touchPage.locator('.tile').nth(3).boundingBox();
