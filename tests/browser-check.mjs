import {chromium} from 'playwright';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('qa',{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1024},deviceScaleFactor:1});
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text());});
const board=[1,2,1,1,2,0,1,2,0,1,1,0,3,1,0,2,1,0,2,1,0,3,1,1,0];
const fixture={board,revealed:[0,1,4,7,12],notes:{2:2,6:6,13:3,15:8,18:4,22:9},history:[],future:[],rounds:[],level:3,bank:1280,coins:24,status:'playing'};
await page.addInitScript(game=>{localStorage.setItem('vf-game',JSON.stringify(game));localStorage.setItem('vf-skin-v2','"club"');},fixture);
await page.goto('http://127.0.0.1:4177/');
await page.evaluate(()=>document.fonts.ready);
await page.getByRole('button',{name:'Edit notes',exact:true}).click();
await page.getByRole('button',{name:'Mark 2',exact:true}).click();
const tile=page.locator('.tile').nth(3);
await tile.focus();await page.waitForTimeout(650);
await page.screenshot({path:'qa/emerald-desktop.png',fullPage:true});
const dimensions=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth,height:document.documentElement.scrollHeight,sidebar:document.querySelector('.play-sidebar').getBoundingClientRect().toJSON(),board:document.querySelector('.board-grid').getBoundingClientRect().toJSON()}));
assert.ok(dimensions.document<=1440,'No desktop horizontal overflow');
// Real pointer gestures, sticky selection and cancellation.
await tile.focus();await page.keyboard.press('Shift+F10');
await page.getByRole('button',{name:'Toggle 1 note',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Toggle 1 note',exact:true}).getAttribute('aria-pressed'),'true');
await page.keyboard.press('Escape');
await page.waitForSelector('.marking-menu',{state:'hidden'});
let b=await tile.boundingBox();const x=b.x+b.width/2,y=b.y+b.height/2;
await page.mouse.move(x,y);await page.mouse.down({button:'right'});await page.waitForTimeout(230);await page.mouse.move(x-40,y-40,{steps:5});await page.mouse.up({button:'right'});
let saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('vf-game')));
assert.ok(saved.notes[3]&4,'Right drag toggles upper-left 1');
assert.equal(saved.revealed.length,5,'Note gestures never reveal');
await page.keyboard.press('ControlOrMeta+z');
