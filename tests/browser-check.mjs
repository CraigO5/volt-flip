await page.keyboard.press('ControlOrMeta+Shift+z');
saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('vf-game')));assert.ok(saved.notes[3]&4,'Redo note');
await page.getByRole('button',{name:'Hints and rules'}).click();await page.waitForSelector('dialog[open]');await page.keyboard.press('Escape');assert.equal(await page.locator('dialog[open]').count(),0);
await page.getByRole('button',{name:'Cash out, collect 24 coins',exact:true}).click();
saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('vf-game')));assert.equal(saved.bank,1304);assert.equal(saved.nextLevel,3);assert.equal(saved.status,'collected');
await page.getByRole('button',{name:'Continue',exact:true}).click();saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('vf-game')));assert.equal(saved.level,3);assert.equal(saved.coins,0);
assert.equal(await page.getByText('Practice options',{exact:true}).count(),0);
// All skin variants preserve the shared grid.
for(const skin of ['plain','neon','pocket','club']){await page.getByRole('combobox').selectOption(skin);assert.equal(await page.locator('.tile').count(),25);}
await page.setViewportSize({width:390,height:844});await page.screenshot({path:'qa/emerald-mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No phone horizontal overflow');
const modeBox=await page.locator('.mode-switch').boundingBox();assert.ok(modeBox.width<=366);
// Real touch context: long hold must not reveal the tile.
